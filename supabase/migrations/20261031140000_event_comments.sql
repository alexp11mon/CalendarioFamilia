-- Spec 014, T1: comments of the events (plan "Modelo de datos", D1, D7, D8;
-- RF-7, RF-9, RF-10, RF-13 to RF-18, RF-22 to RF-24, RF-28).
--
-- A comment belongs to an event: its readers are the members of the event's
-- calendar, so moving or merging needs no change (RF-26) and deleting the
-- event, also from the sync, deletes its comments (RF-18, RF-19).

create table public.event_comments (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events (id) on delete cascade,
  -- Null once the author deletes the account: "Cuenta borrada" (RF-3).
  author_id uuid default auth.uid() references public.profiles (id) on delete set null,
  -- Generated by the form on each send: a double send is saved once (D8).
  client_id uuid not null,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  unique (author_id, client_id)
);

create index event_comments_event_id_idx on public.event_comments (event_id, created_at, id);
create index event_comments_author_id_idx on public.event_comments (author_id);

alter table public.event_comments enable row level security;

-- Clients write the body only; author, dates and event are fixed (RF-17).
revoke all on public.event_comments from anon, authenticated;
grant select, delete on public.event_comments to authenticated;
grant insert (event_id, body, client_id) on public.event_comments to authenticated;
grant update (body) on public.event_comments to authenticated;

-- Members of the event's calendar read, viewers included; someone who left
-- stops reading and their comments stay (RF-22, RF-23).
create policy "event_comments_select_members" on public.event_comments
  for select to authenticated
  using (
    exists (
      select 1 from public.events e
      where e.id = event_comments.event_id
        and public.is_calendar_member(e.calendar_id)
    )
  );

-- Any member comments as themselves, synced calendars included (RF-7, RF-13).
create policy "event_comments_insert_members" on public.event_comments
  for insert to authenticated
  with check (
    author_id = (select auth.uid())
    and exists (
      select 1 from public.events e
      where e.id = event_comments.event_id
        and public.is_calendar_member(e.calendar_id)
    )
  );

-- Only the author edits, while still a member (RF-14, RF-17).
create policy "event_comments_update_author" on public.event_comments
  for update to authenticated
  using (
    author_id = (select auth.uid())
    and exists (
      select 1 from public.events e
      where e.id = event_comments.event_id
        and public.is_calendar_member(e.calendar_id)
    )
  )
  with check (author_id = (select auth.uid()));

-- The author or the calendar's owner deletes; an ownerless calendar has no
-- owner row, so nobody deletes someone else's comment there (RF-15, RF-16).
create policy "event_comments_delete_author_or_owner" on public.event_comments
  for delete to authenticated
  using (
    exists (
      select 1 from public.events e
      where e.id = event_comments.event_id
        and (
          (event_comments.author_id = (select auth.uid())
            and public.is_calendar_member(e.calendar_id))
          or public.calendar_role_for(e.calendar_id) = 'owner'
        )
    )
  );

-- Trims the ends keeping inner line breaks before the length check (RF-9),
-- marks edits (RF-4) and keeps comments off series rows: they go on the row of
-- an occurrence (RF-28, plan D5).
create function public.event_comments_rules()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.body := regexp_replace(new.body, '^\s+|\s+$', '', 'g');

  if tg_op = 'INSERT' then
    if exists (
      select 1 from public.events e
      where e.id = new.event_id and e.recurrence is not null
    ) then
      raise exception 'Comments go on an occurrence, not on the series'
        using errcode = '22023';
    end if;
  elsif new.body is distinct from old.body then
    new.edited_at := now();
  end if;
  return new;
end;
$$;

revoke execute on function public.event_comments_rules() from public, anon, authenticated;

create trigger event_comments_rules
  before insert or update on public.event_comments
  for each row execute function public.event_comments_rules();
